require('dotenv').config();
const {Pool}=require('pg');
const crypto=require('node:crypto');
if(!process.env.DATABASE_URL)throw new Error('Set DATABASE_URL to your Supabase PostgreSQL connection string in .env first.');
const pool=new Pool({connectionString:process.env.DATABASE_URL,max:1,application_name:'repiw-migrations'});
const migrations=[
 {name:'initial_supabase_schema',sql:[
  `CREATE TABLE IF NOT EXISTS cards(id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,code VARCHAR(32) NOT NULL UNIQUE,secret_hash VARCHAR(255) NOT NULL,active SMALLINT NOT NULL DEFAULT 0 CHECK(active IN (0,1)),review_url VARCHAR(2048),activated_at TIMESTAMP, demo SMALLINT NOT NULL DEFAULT 0 CHECK(demo IN (0,1)),created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP)`,
  `CREATE TABLE IF NOT EXISTS visits(id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,card_id BIGINT NOT NULL REFERENCES cards(id) ON DELETE CASCADE,source VARCHAR(3) NOT NULL CHECK(source IN ('qr','nfc')),at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP)`,
  `CREATE TABLE IF NOT EXISTS admins(id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,username VARCHAR(80) NOT NULL UNIQUE,password_hash VARCHAR(255) NOT NULL,created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP)`,
  `CREATE UNIQUE INDEX IF NOT EXISTS idx_admins_username_lower ON admins(LOWER(username))`,
  `CREATE TABLE IF NOT EXISTS sessions(id_hash CHAR(64) PRIMARY KEY,admin_id BIGINT REFERENCES admins(id) ON DELETE CASCADE,expires_at BIGINT NOT NULL,created_at BIGINT NOT NULL)`,
  `CREATE INDEX IF NOT EXISTS idx_sessions_admin ON sessions(admin_id)`,
  `CREATE INDEX IF NOT EXISTS idx_sessions_expires ON sessions(expires_at)`,
  `CREATE TABLE IF NOT EXISTS rate_events(id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,bucket VARCHAR(100) NOT NULL,at BIGINT NOT NULL)`,
  `CREATE INDEX IF NOT EXISTS idx_rate_events_bucket_at ON rate_events(bucket,at)`,
  `CREATE INDEX IF NOT EXISTS idx_visits_card_source ON visits(card_id,source)`,
  `CREATE INDEX IF NOT EXISTS idx_cards_created ON cards(created_at DESC)`,
  `CREATE INDEX IF NOT EXISTS idx_cards_demo_created ON cards(demo,created_at DESC)`,
  `CREATE TABLE IF NOT EXISTS schema_migrations(version INTEGER PRIMARY KEY,name TEXT NOT NULL,checksum CHAR(64) NOT NULL,applied_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP)`,
  `CREATE TABLE IF NOT EXISTS data_imports(source_key CHAR(64) PRIMARY KEY,cards_count INTEGER NOT NULL,visits_count INTEGER NOT NULL,imported_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP)`
 ]},
 {name:'attach_sessions_to_admins',sql:[
  `ALTER TABLE sessions ADD COLUMN IF NOT EXISTS admin_id BIGINT REFERENCES admins(id) ON DELETE CASCADE`,
  `CREATE INDEX IF NOT EXISTS idx_sessions_admin ON sessions(admin_id)`,
  `DELETE FROM sessions WHERE admin_id IS NULL`,
  `CREATE TABLE IF NOT EXISTS data_imports(source_key CHAR(64) PRIMARY KEY,cards_count INTEGER NOT NULL,visits_count INTEGER NOT NULL,imported_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP)`
 ]},
 {name:'normalize_card_flags',sql:[
  `DO $migration$ DECLARE flag_type TEXT; BEGIN SELECT data_type INTO flag_type FROM information_schema.columns WHERE table_schema=current_schema() AND table_name='cards' AND column_name='active'; IF flag_type='boolean' THEN ALTER TABLE cards ALTER COLUMN active DROP DEFAULT; ALTER TABLE cards ALTER COLUMN active TYPE SMALLINT USING CASE WHEN active THEN 1 ELSE 0 END; ALTER TABLE cards ALTER COLUMN active SET DEFAULT 0; END IF; END $migration$`
 ]},
 {name:'track_nfc_card_programming',sql:[
  `ALTER TABLE cards ADD COLUMN IF NOT EXISTS nfc_registered_at TIMESTAMP`
 ]},
 {name:'retain_encrypted_activation_codes',sql:[
  `ALTER TABLE cards ADD COLUMN IF NOT EXISTS activation_code_encrypted TEXT`
 ]}
];
(async()=>{
 const client=await pool.connect();
 try{
  await client.query('SELECT 1');
  await client.query(`CREATE TABLE IF NOT EXISTS schema_migrations(version INTEGER PRIMARY KEY,name TEXT NOT NULL,checksum CHAR(64) NOT NULL,applied_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP)`);
  const current=await client.query('SELECT COALESCE(MAX(version),0) AS version FROM schema_migrations');
  for(let i=Number(current.rows[0].version);i<migrations.length;i++){
   const m=migrations[i], checksum=crypto.createHash('sha256').update(m.sql.join(';\n')).digest('hex');
   await client.query('BEGIN');
   try{
    for(const statement of m.sql)await client.query(statement);
    await client.query('INSERT INTO schema_migrations(version,name,checksum) VALUES($1,$2,$3)',[i+1,m.name,checksum]);
    await client.query('COMMIT');
   }catch(error){await client.query('ROLLBACK');throw error;}
  }
  const counts={};
  for(const table of ['cards','visits','admins']){const result=await client.query(`SELECT COUNT(*) AS n FROM ${table}`);counts[table]=Number(result.rows[0].n);}
  await client.query('DELETE FROM sessions WHERE expires_at <= $1',[Date.now()]);
  const dbinfo=await client.query('SELECT current_database() AS database,current_schema() AS schema');
  console.log(JSON.stringify({ok:true,...dbinfo.rows[0],schemaVersion:migrations.length,rows:counts},null,2));
 }finally{client.release();await pool.end();}
})().catch(async error=>{console.error(`Supabase migration failed: ${error.message}`);await pool.end();process.exit(1);});
